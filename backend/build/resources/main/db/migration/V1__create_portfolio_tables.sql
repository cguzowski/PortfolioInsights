CREATE TABLE portfolio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    portfolio_name VARCHAR(120) NOT NULL,
    base_currency CHAR(3) NOT NULL DEFAULT 'USD',
    risk_profile VARCHAR(30) NOT NULL,
    cash_balance NUMERIC(18, 2) NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE portfolio_holding (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id BIGINT NOT NULL REFERENCES portfolio(id) ON DELETE CASCADE,
    ticker VARCHAR(10) NOT NULL,
    security_name VARCHAR(120) NOT NULL,
    asset_class VARCHAR(30) NOT NULL,
    quantity NUMERIC(18, 4) NOT NULL,
    average_cost NUMERIC(18, 4) NOT NULL,
    current_price NUMERIC(18, 4) NOT NULL,
    change_percent NUMERIC(7, 4) NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
